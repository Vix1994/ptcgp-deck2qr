export function initialLanguage(storedLanguage, browserLanguage) {
  if (storedLanguage === 'zh' || storedLanguage === 'en') return storedLanguage;
  return browserLanguage?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function translate(language, key, values = {}) {
  const template = COPY[language]?.[key] ?? COPY.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function styleLabel(language, style) {
  return STYLE_LABELS[language]?.[style] ?? style;
}

export function errorLabel(language, error) {
  return ERROR_LABELS[language]?.[error] ?? error;
}
